"""One synthetic visit, bay camera: ground truth vs noisy per-frame predictions vs decoded states (baseline / HMM).

    python -m sim.plot_timeline OUT.png [--acc 0.85] [--corr 10] [--visit 3]
"""
from __future__ import annotations

import argparse

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from seen import hmm, visit_engine  # noqa: E402
from sim import noise_test as NT  # noqa: E402
from sim.scenario import generate_visits  # noqa: E402

SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
ON = "#2a78d6"
LABELS = ["car_present", "raised", "wheel_off", "hood_open", "person_under_car", "work", "idle"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--acc", type=float, default=0.85)
    ap.add_argument("--corr", type=float, default=10.0)
    ap.add_argument("--visit", type=int, default=3)
    a = ap.parse_args()
    visit, wo, tl = generate_visits(a.visit + 1, NT.TEST_SEED)[a.visit]
    preds, t_end, _, _ = NT.make_preds(tl, "bay", NT.Noise(a.acc, a.corr), np.random.default_rng(1))
    times = np.array([p.t_s for p in preds])
    P, M = visit_engine._state_matrix(preds)
    dec = {"Threshold + hysteresis": hmm.hysteresis(P, M), "HMM + scenario priors": hmm.decode(times, P, M, zone_kind="bay")}
    gt_t, gt_lab = tl.view("bay", 0, 0)
    rows = [("Ground truth", None)] + [("Per-frame input (p > 0.5)", None)] + [(k, v) for k, v in dec.items()]
    fig, axes = plt.subplots(len(rows), 1, figsize=(11, 7.5), sharex=True, facecolor=SURFACE)
    t0 = times[0]
    for ax, (name, d) in zip(axes, rows):
        ax.set_facecolor(SURFACE)
        for j, lab in enumerate(LABELS):
            k = hmm.LIDX[lab]
            if name == "Ground truth":
                xs, on = gt_t, gt_lab[:, k].astype(bool)
            elif d is None:
                xs = times
                on = (P[:, k] > 0.5) if lab != "idle" else (P[:, hmm.LIDX["car_present"]] > 0.5) & (P[:, hmm.LIDX["work"]] <= 0.5)
            else:
                xs, on = times, d.labels[:, k]
                if lab == "idle":
                    on = d.labels[:, hmm.LIDX["car_present"]] & ~d.labels[:, hmm.LIDX["work"]]
            for s, e in hmm.segments(on):
                x0 = (xs[s] - t0) / 60
                x1 = ((xs[e] if e is not None else xs[-1]) - t0) / 60
                ax.add_patch(plt.Rectangle((x0, j + 0.15), max(x1 - x0, 0.02), 0.7, color=ON, linewidth=0))
        ax.set_ylim(0, len(LABELS))
        ax.set_yticks(np.arange(len(LABELS)) + 0.5, LABELS, fontsize=8, color=INK2)
        ax.invert_yaxis()
        ax.set_title(name, loc="left", fontsize=10, color=INK)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        ax.spines["left"].set_color(GRID)
        ax.spines["bottom"].set_color(GRID)
        ax.tick_params(colors=INK2)
        ax.grid(True, axis="x", color=GRID, linewidth=0.8)
    axes[-1].set_xlim(0, (times[-1] - t0) / 60)
    axes[-1].set_xlabel("Minutes (bay camera)", color=INK2)
    fig.text(0.01, 0.005, f"SYNTHETIC visit {tl.visit_id} ({tl.meta['job_type']}); simulated per-frame accuracy {a.acc:.0%}, "
             f"errors lasting ~{a.corr:.0f} s, 0.5–2 fps. Generated by sim/plot_timeline.py.", fontsize=7.5, color=INK2)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(a.out, dpi=140, facecolor=SURFACE)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
