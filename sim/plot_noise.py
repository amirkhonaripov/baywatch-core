"""Curves "per-frame accuracy -> event accuracy" from sim/noise_test.py output (synthetic, perception-free).

    python -m sim.plot_noise RUN_DIR OUT.png
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
SERIES = {  # validated categorical slots 1-3 (dataviz reference palette, all-pairs, light mode)
    "hmm_fitted": ("#2a78d6", "o", "HMM + scenario priors"),
    "hmm_generic": ("#eb6834", "s", "HMM, grammar only"),
    "baseline_hysteresis": ("#1baf7a", "^", "Threshold + hysteresis"),
}
ROWS = [
    ("key_f1_10s", "Key-event F1 (±10 s)"),
    ("idle_f1", "Idle-span F1 (IoU ≥ 0.5)"),
    ("line_bal_acc_keyed", "Work-order line status\nbalanced accuracy vs oracle"),
]
COLS = [(0.0, "Independent errors (flicker)"), (10.0, "Errors last ~10 s"), (60.0, "Errors last ~60 s")]


def f1(p, r):
    if p != p or r != r or p + r == 0:  # NaN or zero
        return 0.0
    return 2 * p * r / (p + r)


def main(run_dir: str, out: str) -> None:
    grid = [g for g in json.loads((Path(run_dir) / "grid.json").read_text()) if g["cond"] == "grid"]
    for g in grid:
        g["idle_f1"] = f1(g["idle_seg_precision"], g["idle_seg_recall"])
        g["line_bal_acc_keyed"] = (g["line_evidence_recall_keyed"] + g["line_not_observed_recall_keyed"]) / 2
    plt.rcParams.update({"font.size": 9, "axes.edgecolor": GRID, "axes.labelcolor": INK2, "xtick.color": INK2,
                         "ytick.color": INK2, "text.color": INK})
    fig, axes = plt.subplots(len(ROWS), len(COLS), figsize=(11, 8.2), sharex=True, sharey="row", facecolor=SURFACE)
    for r, (key, ylabel) in enumerate(ROWS):
        for c, (corr, title) in enumerate(COLS):
            ax = axes[r][c]
            ax.set_facecolor(SURFACE)
            ax.grid(True, color=GRID, linewidth=0.8)
            ax.set_axisbelow(True)
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            for dec, (col, mk, label) in SERIES.items():
                pts = sorted((g["frame_acc_measured"], g[key]) for g in grid if g["corr_s"] == corr and g["decoder"] == dec)
                xs, ys = zip(*pts)
                ax.plot(xs, ys, color=col, linewidth=2, marker=mk, markersize=6, markeredgecolor=SURFACE,
                        markeredgewidth=1.2, label=label)
                if r == 0 and c == 2 and dec == "baseline_hysteresis":  # direct label (contrast relief for aqua)
                    ax.annotate(label, (xs[-1], ys[-1]), xytext=(6, 0), textcoords="offset points", va="center",
                                fontsize=8, color=INK2)
            ax.set_ylim(-0.03, 1.03)
            if r == 0:
                ax.set_title(title, fontsize=10, color=INK, loc="left")
            if c == 0:
                ax.set_ylabel(ylabel)
            if r == len(ROWS) - 1:
                ax.set_xlabel("Per-frame accuracy of the state predictor")
    handles, labels = axes[0][0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=3, frameon=False, bbox_to_anchor=(0.5, 0.995))
    fig.text(0.01, 0.006, "SYNTHETIC, perception-free: scenario-engine timelines with simulated per-frame noise; 120 visits per "
             "point, 0.5–2 fps, 10% of frames dropped.\nLine status: mean of evidence-found and not-observed recall, "
             "zone/state-keyed spans (see docs/lanes/sim_notes.md). Generated by sim/noise_test.py and sim/plot_noise.py.",
             fontsize=7.5, color=INK2)
    fig.tight_layout(rect=(0, 0.035, 0.9, 0.96))
    fig.savefig(out, dpi=150, facecolor=SURFACE)
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
